/**
 * The knight, as a mesh.
 *
 * Everything about this piece used to be hand-authored: a side profile typed
 * out as a list of millimetre coordinates, lofted by scanline into something
 * with depth. That got a long way — far enough to read as a chess knight —
 * but a horse's head is a sculpture, not a curve, and past a certain point
 * you are not tuning a silhouette any more, you are trying to carve one
 * numerically. The jaw, the cheekbone, the way the mane wraps around the far
 * side of the neck, the flare of a nostril: none of those are functions of
 * height, and none of them survive being written as one.
 *
 * So it is a real model now — a 617k-triangle ZBrush Staunton knight, quadric
 * decimated to 2,600 triangles and baked in here. 2,600 is where the
 * silhouette stops changing: at that count the ear tips, the eye socket, the
 * scalloped mane and the turned rings of the pedestal all survive, and going
 * finer only adds vertices the point cloud will never resolve.
 *
 * The mesh is never rendered. It exists to be sampled by `knightShape` and is
 * otherwise invisible, which is the whole reason the result reads as a
 * constellation rather than as a chess piece with sparkles on it.
 *
 * The encoding is deliberately dull. Positions are 16-bit fixed point over
 * the bounding box, indices are 16-bit (1,301 vertices leaves plenty of
 * headroom), and the lot is base64 — about 31kB of source, decoded once,
 * lazily, the first time a knight is asked for. That is cheaper than a fetch:
 * no request, no loading state, no shape that pops into place a second after
 * the scroll reaches it, and no failure mode in which the finale of the page
 * is a 404.
 *
 * Normalised on the way in, so nothing downstream has to know how the file
 * was authored: rotated so the muzzle faces -x, centred on the axis of its
 * own pedestal — taken from the bottom 8% of the model, so the piece turns
 * about the middle of its base rather than about the middle of its bounding
 * box — scaled to unit height, and widened by 12% on the two horizontal axes
 * to put the base at the specified 78mm on a 160mm piece. The source model is
 * a little narrower than the drawing, and a knight that is even slightly too
 * slender reads as a bishop at a glance.
 */

