export type KnightMesh = {
  /** Vertex positions, xyz triples, unit height. */
  positions: Float32Array;
  /** Triangle indices. */
  indices: Uint16Array;
  /** Cumulative sampling weight for an even skin, normalised to 1. */
  cumulativeSkin: Float32Array;
  /** Cumulative sampling weight biased toward small triangles — the features. */
  cumulativeDetail: Float32Array;
  /** Per-triangle unit outward normal, xyz triples. */
  normals: Float32Array;
};

let cached: KnightMesh | null = null;

/** Decode, then build the area table and the face normals. Done once, on first use. */
export function knightMesh(): KnightMesh {
  if (cached) return cached;

  const binary = atob(DATA);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  const words = new Uint16Array(bytes.buffer, bytes.byteOffset, bytes.length >> 1);

  const vertexCount = words[0];
  const triangleCount = words[1];

  const positions = new Float32Array(vertexCount * 3);
  for (let i = 0; i < vertexCount * 3; i++) {
    const axis = i % 3;
    positions[i] = LO[axis] + (words[2 + i] / 65535) * SIZE[axis];
  }

  const first = 2 + vertexCount * 3;
  const indices = new Uint16Array(triangleCount * 3);
  indices.set(words.subarray(first, first + triangleCount * 3));

  const normals = new Float32Array(triangleCount * 3);
  const cumulativeSkin = new Float32Array(triangleCount);
  const cumulativeDetail = new Float32Array(triangleCount);
  let skin = 0;
  let detail = 0;
  for (let t = 0; t < triangleCount; t++) {
    const ia = indices[t * 3] * 3;
    const ib = indices[t * 3 + 1] * 3;
    const ic = indices[t * 3 + 2] * 3;
    const ux = positions[ib] - positions[ia];
    const uy = positions[ib + 1] - positions[ia + 1];
    const uz = positions[ib + 2] - positions[ia + 2];
    const vx = positions[ic] - positions[ia];
    const vy = positions[ic + 1] - positions[ia + 1];
    const vz = positions[ic + 2] - positions[ia + 2];
    const nx = uy * vz - uz * vy;
    const ny = uz * vx - ux * vz;
    const nz = ux * vy - uy * vx;
    const len = Math.hypot(nx, ny, nz) || 1;
    normals[t * 3] = nx / len;
    normals[t * 3 + 1] = ny / len;
    normals[t * 3 + 2] = nz / len;
    /*
     * Half the cross product's length is the triangle's area, and plain area
     * weighting is the textbook way to sample a surface uniformly. It is also,
     * on this model, catastrophic.
     *
     * The pedestal carries a wide flat collar — a saucer, near enough — and
     * between its top and bottom annuli that one feature holds thirty per cent
     * of the model's entire surface area. Sampled by area, thirty per cent of
     * the cloud lands on it: the knight came out as a horizontal disc of dust
     * with a faint horse above it. The collar is not hidden geometry and
     * deleting it would be wrong — it is a real, visible step in the turning —
     * it simply happens to be enormous and, to a camera looking at the piece
     * from almost dead level, edge on.
     *
     * So the weight is the area *projected toward a horizontal viewer*: the
     * horizontal component of the normal, with a small floor so a flat face
     * is quietened rather than deleted. Faces you see across get their points;
     * faces you see edge on get a line's worth, which is exactly what they
     * occupy on screen.
     */
    const area = len * 0.5;
    const horizontal = 0.06 + 0.94 * Math.sqrt(Math.max(0, 1 - normals[t * 3 + 1] ** 2));
    skin += area * horizontal;
    cumulativeSkin[t] = skin;
    /*
     * The detail table trades area for triangle count. A quadric decimator
     * spends its budget where the surface is interesting, so small triangles
     * *are* the ear tips, the eye socket, the nostril, the scallops of the
     * mane and the turned rings of the pedestal. Weighting by the square root
     * of area rather than area pulls sampling toward them without going all
     * the way to one-point-per-triangle, which would hand a third of the band
     * to the collar again — it is 900 triangles, they are just small ones.
     */
    detail += area ** 0.45 * horizontal;
    cumulativeDetail[t] = detail;
  }
  for (let t = 0; t < triangleCount; t++) {
    cumulativeSkin[t] /= skin;
    cumulativeDetail[t] /= detail;
  }

  cached = { positions, indices, cumulativeSkin, cumulativeDetail, normals };
  return cached;
}